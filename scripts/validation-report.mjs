// Runs every physics test file separately and writes docs/validation-run.md: one row per test
// group, with pass/fail, the module it belongs to, and the exact code version and runtime.
// Usage: pnpm validate   (or: node scripts/validation-report.mjs)
import { execFileSync, spawnSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MODULE_OF = {
  'segregation.test.ts': '01 Silica to wafer (Scheil)',
  'growth.test.ts': '01 Silica to wafer (thermal growth)',
  'atomicPhysics.test.ts': '02 Atoms to bands',
  'equilibrium.test.ts': '03 Equilibrium carriers',
  'transport.test.ts': '04 Transport & lifetime',
  'fabrication.test.ts': '05 Fabricate a MOSFET',
  'junction.test.ts': '06 P–n junction',
  'physics.test.ts': '06 P–n junction (legacy Neamen-example reference)',
  'diode.test.ts': '07 PN diode',
  'mos.test.ts': '08 Gate control',
  'photonics.test.ts': '09 Photonic devices',
  'bench.test.ts': '10 Measurement bench',
  'materials.test.ts': 'Shared material parameters',
  'modules.test.ts': 'Shared navigation registry',
};

const git = (...a) => {
  try {
    return execFileSync('git', a, { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
};
const commit = git('rev-parse', '--short', 'HEAD');
const dirty = git('status', '--porcelain', '--', 'src') ? ' (with uncommitted changes in src/)' : '';

const files = readdirSync('src').filter((f) => f.endsWith('.test.ts')).sort();
const rows = [];
let failed = 0;
for (const f of files) {
  const r = spawnSync(process.execPath, ['--import', 'tsx', '--test', '--test-reporter=tap', join('src', f)], {
    encoding: 'utf8',
  });
  for (const line of r.stdout.split('\n')) {
    const m = /^(ok|not ok) \d+ - (.*)$/.exec(line);
    if (!m) continue;
    const pass = m[1] === 'ok';
    if (!pass) failed++;
    rows.push({ module: MODULE_OF[f] ?? f, file: f, name: m[2].replace(/\|/g, '\\|'), pass });
  }
  if (r.status !== 0 && !rows.some((x) => x.file === f && !x.pass)) {
    failed++;
    rows.push({ module: MODULE_OF[f] ?? f, file: f, name: '(file failed to run)', pass: false });
  }
}

const date = new Date().toISOString().slice(0, 10);
const out = [
  '# Automated validation run',
  '',
  `Generated by \`scripts/validation-report.mjs\` on ${date} at commit \`${commit}\`${dirty}, Node ${process.version}.`,
  'Regenerate with `pnpm validate`. This file records implementation verification (analytical limits,',
  'conservation, independent reference calculations, refinement). It is not agreement with physical',
  'measurements; see docs/validation.md for the matrix and what each check does and does not establish.',
  '',
  `**${rows.length - failed} of ${rows.length} test groups pass.**`,
  '',
  '| Module | Test group | File | Result |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.module} | ${r.name} | \`src/${r.file}\` | ${r.pass ? 'pass' : '**FAIL**'} |`),
  '',
].join('\n');
writeFileSync('docs/validation-run.md', out);
console.log(`${rows.length - failed}/${rows.length} pass -> docs/validation-run.md`);
process.exit(failed ? 1 : 0);
